"""Import the central Timișoara road network from OpenStreetMap into an offline snapshot.

OWNER: Rareș (network). Two steps, so the slow/online part runs once:

    python scripts/import_osm_network.py fetch   # Overpass -> data/osm/raw_centre.json (needs network)
    python scripts/import_osm_network.py build   # raw -> data/network/timisoara_centre.json (offline)
    python scripts/import_osm_network.py all     # both

The snapshot is committed; the raw Overpass dump is not (it is regenerated by ``fetch``).

Graph construction
------------------
* Nodes are OSM nodes where two or more drivable ways meet, way ends, and dead ends.
  Shape points in between become link geometry (degree-2 contraction).
* Each way piece between two nodes becomes one directed link per allowed direction
  (``oneway=yes|-1``, roundabouts are one-way).
* Lanes per direction: ``lanes:forward/backward`` > ``lanes`` (split for two-way) > class default.
* Speed: ``maxspeed`` (numeric or ``RO:urban``) > class default.
* A node is signalised if it is tagged ``highway=traffic_signals`` or a signal node lies on
  an incident link within ``SIGNAL_SNAP_M`` of it (OSM often tags the stop line, not the junction).
* Only the largest strongly connected component is kept, so every OD is routable.
"""
from __future__ import annotations

import argparse
import json
import math
import re
import sys
import time
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))

RAW_PATH = BACKEND / "data" / "osm" / "raw_centre.json"
SNAPSHOT_PATH = BACKEND / "data" / "network" / "timisoara_centre.json"

# Central Timișoara (south, west, north, east) — same box as the cycling layer.
BBOX = (45.725, 21.190, 45.780, 21.265)
OVERPASS_URLS = [
    "https://overpass-api.de/api/interpreter",
    "https://overpass.kumi.systems/api/interpreter",
    "https://overpass.private.coffee/api/interpreter",
]
USER_AGENT = "TM-BraessGreen-UniHack/1.0 (Timisoara Green Mobility Simulator)"

# Drivable classes kept. Residential streets matter: the Braess cut-throughs run on them.
HIGHWAY_CLASSES = (
    "trunk", "trunk_link", "primary", "primary_link", "secondary", "secondary_link",
    "tertiary", "tertiary_link", "unclassified", "residential",
)
# (lanes per direction, free-flow speed km/h, capacity veh/h per lane) by class.
CLASS_DEFAULTS: dict[str, tuple[int, float, float]] = {
    "trunk": (2, 60, 1000), "primary": (2, 50, 900), "secondary": (1, 50, 850),
    "tertiary": (1, 40, 800), "unclassified": (1, 40, 700), "residential": (1, 30, 600),
}
SIGNAL_SNAP_M = 35.0


def _base_class(highway: str) -> str:
    return highway.removesuffix("_link")


def overpass_query() -> str:
    s, w, n, e = BBOX
    classes = "|".join(HIGHWAY_CLASSES)
    return f"""
[out:json][timeout:90];
(
  way["highway"~"^({classes})$"]["access"!~"^(no|private)$"]["area"!="yes"]({s},{w},{n},{e});
);
(._;>;);
out body;
"""


# ---------------------------------------------------------------------------
# fetch
# ---------------------------------------------------------------------------

def fetch() -> None:
    import httpx

    print(f"Querying Overpass for bbox {BBOX} ...")
    t = time.perf_counter()
    raw = None
    for attempt, url in enumerate(OVERPASS_URLS * 2):
        try:
            r = httpx.post(url, data={"data": overpass_query()}, headers={"User-Agent": USER_AGENT}, timeout=180)
            r.raise_for_status()
            raw = r.json()
            print(f"  ok from {url}")
            break
        except (httpx.HTTPError, ValueError) as exc:
            print(f"  {url} failed ({exc.__class__.__name__}: {str(exc)[:80]}); trying next")
            time.sleep(3 + attempt * 2)
    if raw is None:
        raise SystemExit("All Overpass endpoints failed; try again later.")
    raw["_fetched_at"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
    RAW_PATH.parent.mkdir(parents=True, exist_ok=True)
    RAW_PATH.write_text(json.dumps(raw), encoding="utf-8")
    n_ways = sum(1 for e in raw["elements"] if e["type"] == "way")
    print(f"Saved {len(raw['elements'])} elements ({n_ways} ways) to {RAW_PATH} in {time.perf_counter() - t:.1f}s")


