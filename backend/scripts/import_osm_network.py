# build
# ---------------------------------------------------------------------------

def _dist_m(a: tuple[float, float], b: tuple[float, float]) -> float:
    lng1, lat1 = map(math.radians, a)
    lng2, lat2 = map(math.radians, b)
    h = math.sin((lat2 - lat1) / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin((lng2 - lng1) / 2) ** 2
    return 2 * 6_371_000 * math.asin(math.sqrt(h))


def _parse_int(v: str | None) -> int | None:
    if not v:
        return None
    m = re.match(r"\s*(\d+)", v.split(";")[0])
    return int(m.group(1)) if m else None


def _parse_speed(v: str | None) -> float | None:
    if not v:
        return None
    v = v.strip().lower()
    if v in ("ro:urban", "urban"):
        return 50.0
    m = re.match(r"(\d+(?:\.\d+)?)\s*(mph)?", v)
    if not m:
        return None
    s = float(m.group(1))
    return s * 1.609 if m.group(2) else s


def _oneway(tags: dict[str, str]) -> int:
    """+1 forward only, -1 backward only, 0 two-way."""
    ow = tags.get("oneway", "").lower()
    if ow in ("yes", "true", "1"):
        return 1
    if ow == "-1" or ow == "reverse":
        return -1
    if ow == "no":
        return 0
    if tags.get("junction") in ("roundabout", "circular") or tags.get("highway") in ("motorway", "motorway_link"):
        return 1
    return 0


def _lanes_per_direction(tags: dict[str, str], oneway: int, default: int) -> tuple[int, int]:
    total = _parse_int(tags.get("lanes"))
    fwd = _parse_int(tags.get("lanes:forward"))
    bwd = _parse_int(tags.get("lanes:backward"))
    if oneway != 0:
        n = total or fwd or bwd or default
        return (n, 0) if oneway == 1 else (0, n)
    if fwd is None and bwd is None:
        if total:
            half = max(total // 2, 1)
            return max(total - half, 1), half
        return default, default
    if fwd is None:
        fwd = max((total or 2 * bwd) - bwd, 1)
    if bwd is None:
        bwd = max((total or 2 * fwd) - fwd, 1)
    return max(fwd, 1), max(bwd, 1)


def _psv_lanes(tags: dict[str, str], oneway: int, lf: int, lb: int) -> tuple[int, int]:
    """Bus (PSV) lanes per direction, taken out of the directional lane counts."""
    fwd = _parse_int(tags.get("lanes:psv:forward"))
    bwd = _parse_int(tags.get("lanes:psv:backward"))
    tot = _parse_int(tags.get("lanes:psv"))
    if fwd is None and bwd is None and tot:
        if oneway == 1:
            fwd = tot
        elif oneway == -1:
            bwd = tot
        else:
            fwd, bwd = tot - tot // 2, tot // 2
    # never leave a direction without a car lane
    return min(fwd or 0, max(lf - 1, 0)), min(bwd or 0, max(lb - 1, 0))


def _largest_scc(node_ids: set[str], links: list[dict]) -> set[str]:
    import networkx as nx

    g = nx.DiGraph()
    g.add_nodes_from(node_ids)
    g.add_edges_from((l["from"], l["to"]) for l in links)
    return max(nx.strongly_connected_components(g), key=len)


def _cartier_lookup():
    """Nearest seed-network node's cartier (the seed nodes are hand-labelled by neighbourhood)."""
    from app.seed.network import NODES

    pts = [(lng, lat, cart) for (_, lng, lat, cart, _) in NODES.values()]

    def lookup(lng: float, lat: float) -> str:
        return min(pts, key=lambda p: (p[0] - lng) ** 2 + ((p[1] - lat) * 1.43) ** 2)[2]

    return lookup


def build() -> dict[str, Any]:
    raw = json.loads(RAW_PATH.read_text(encoding="utf-8"))
    osm_nodes: dict[int, dict] = {}
    ways: list[dict] = []
    for el in raw["elements"]:
        if el["type"] == "node":
            osm_nodes[el["id"]] = el
        elif el["type"] == "way":
            ways.append(el)

    # ---- 1. which OSM nodes are graph nodes -------------------------------
    use = Counter()
    for w in ways:
        for nid in w["nodes"]:
            use[nid] += 1
    graph_node: set[int] = set()
    for w in ways:
        graph_node.add(w["nodes"][0])
        graph_node.add(w["nodes"][-1])
        graph_node.update(n for n in w["nodes"] if use[n] >= 2)
    signal_nodes = {nid for nid, n in osm_nodes.items() if n.get("tags", {}).get("highway") == "traffic_signals"}

    def ll(nid: int) -> tuple[float, float]:
        n = osm_nodes[nid]
        return (n["lon"], n["lat"])

    # ---- 2. split ways into pieces between graph nodes --------------------
    links: list[dict] = []
    signalised: set[int] = set(signal_nodes & graph_node)
    streets_at: dict[int, set[str]] = defaultdict(set)
    for w in ways:
        tags = w.get("tags", {})
        hw = tags.get("highway", "")
        cls = _base_class(hw)
        d_lanes, d_speed, d_cap = CLASS_DEFAULTS.get(cls, CLASS_DEFAULTS["residential"])
        ow = _oneway(tags)
        lf, lb = _lanes_per_direction(tags, ow, d_lanes)
        bf, bb = _psv_lanes(tags, ow, lf, lb)
        lanes_f = ["car"] * (lf - bf) + ["bus"] * bf     # curb-side bus lane last, as in the seed
        lanes_b = ["car"] * (lb - bb) + ["bus"] * bb
        speed = _parse_speed(tags.get("maxspeed")) or d_speed
        name = tags.get("name") or tags.get("ref") or f"({hw})"
        seq = w["nodes"]
        start = 0
        piece = 0
        for i in range(1, len(seq)):
            if seq[i] not in graph_node:
                continue
            chunk = seq[start:i + 1]
            start = i
            if len(chunk) < 2 or chunk[0] == chunk[-1]:
                continue  # skip degenerate self-loops
            coords = [ll(n) for n in chunk]
            length = sum(_dist_m(coords[k], coords[k + 1]) for k in range(len(coords) - 1))
            if length < 1.0:
                continue
            # a signal on this piece marks only its NEAREST end node, and only within SIGNAL_SNAP_M
            acc = 0.0
            for k in range(1, len(chunk) - 1):
                acc += _dist_m(coords[k - 1], coords[k])
                if chunk[k] in signal_nodes:
                    near_start = acc <= length - acc
                    if min(acc, length - acc) <= SIGNAL_SNAP_M:
                        signalised.add(chunk[0] if near_start else chunk[-1])
            streets_at[chunk[0]].add(name)
            streets_at[chunk[-1]].add(name)
            base = f"L{w['id']}_{piece}"
            piece += 1
            common = {"street": name, "highway": hw, "speed_kmh": round(speed, 1), "length_m": round(length, 1),
                      "lane_capacity": d_cap, "osm_way": w["id"]}
            rounded = [[round(x, 5), round(y, 5)] for x, y in coords]   # 1e-5° ≈ 1 m
            fwd_id, bwd_id = f"{base}_01", f"{base}_02"
            if lf > 0:
                links.append({"id": fwd_id, "twin": bwd_id if lb > 0 else None, "from": f"N{chunk[0]}",
                              "to": f"N{chunk[-1]}", "lanes": lanes_f, "coords": rounded, **common})
            if lb > 0:
                links.append({"id": bwd_id, "twin": fwd_id if lf > 0 else None, "from": f"N{chunk[-1]}",
                              "to": f"N{chunk[0]}", "lanes": lanes_b, "coords": rounded[::-1], **common})

    # ---- 3. keep the largest strongly connected component -----------------
    all_nodes = {l["from"] for l in links} | {l["to"] for l in links}
    keep = _largest_scc(all_nodes, links)
    links = [l for l in links if l["from"] in keep and l["to"] in keep]
    ids = {l["id"] for l in links}
    for l in links:
        if l["twin"] not in ids:
            l["twin"] = None

    # ---- 4. node table -----------------------------------------------------
    cartier = _cartier_lookup()
    nodes = []
    for nid_s in sorted(keep, key=lambda s: int(s[1:])):
        nid = int(nid_s[1:])
        lng, lat = ll(nid)
        names = sorted(n for n in streets_at[nid] if not n.startswith("("))
        nodes.append({
            "id": nid_s,
            "name": " / ".join(names[:2]) if names else f"OSM node {nid}",
            "lng": round(lng, 6), "lat": round(lat, 6),
            "cartier": cartier(lng, lat),
            "signalized": nid in signalised,
            "osm_node": nid,
        })

    snapshot = {
        "meta": {
            "source": "OpenStreetMap via Overpass API",
            "attribution": "© OpenStreetMap contributors (ODbL)",
            "bbox_swne": list(BBOX),
            "highway_classes": list(HIGHWAY_CLASSES),
            "fetched_at": raw.get("_fetched_at"),
            "built_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "n_nodes": len(nodes),
            "n_links": len(links),
            "n_signalized": sum(1 for n in nodes if n["signalized"]),
            "defaults": {k: {"lanes_per_dir": v[0], "speed_kmh": v[1], "lane_capacity": v[2]}
                         for k, v in CLASS_DEFAULTS.items()},
        },
        "nodes": nodes,
        "links": links,
    }
    SNAPSHOT_PATH.parent.mkdir(parents=True, exist_ok=True)
    SNAPSHOT_PATH.write_text(json.dumps(snapshot, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    m = snapshot["meta"]
    size_kb = SNAPSHOT_PATH.stat().st_size / 1024
    print(f"Snapshot: {m['n_nodes']} nodes, {m['n_links']} links, {m['n_signalized']} signalised "
          f"-> {SNAPSHOT_PATH} ({size_kb:.0f} kB)")
    return snapshot


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("step", choices=["fetch", "build", "all"])
    args = ap.parse_args()
    if args.step in ("fetch", "all"):
        fetch()
    if args.step in ("build", "all"):
        build()


if __name__ == "__main__":
    main()
